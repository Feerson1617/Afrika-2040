"""Offline, reproducible projection of official Natural Earth GeoJSON. No hand-drawn borders."""
import json,hashlib,sys
from pathlib import Path
source=Path(sys.argv[1]);dest=Path('src/geography')
countries=json.loads((source/'countries.geojson').read_text())['features'];places=json.loads((source/'places.geojson').read_text())['features']
africa=[]
for f in countries:
 p=f['properties']
 if p['CONTINENT']!='Africa':continue
 africa.append({'code':p['ADM0_A3'],'name':p['NAME_DE'],'region':p['SUBREGION'],'geometry':f['geometry']})
selected={}
for city,code in [('Nairobi','KEN'),('Kumasi','GHA'),('Agadir','MAR')]:
 p=next(f['properties']for f in places if f['properties']['name']==city)
 selected[code]={'city':city,'longitude':p['longitude'],'latitude':p['latitude'],'country':p['adm0name']}
# Keep the complete used coordinates for independent validation and regeneration.
(dest/'natural-earth-africa.json').write_text(json.dumps({'countries':africa,'places':selected},ensure_ascii=False,separators=(',',':'))+'\n')
def project(p):return [round(24+(p[0]+20)*9.2,3),round(24+(38-p[1])*9.2,3)]
def path(g):
 polys=g['coordinates'] if g['type']=='MultiPolygon'else[g['coordinates']]
 return ''.join('M'+'L'.join(','.join(map(str,project(p)))for p in ring)+'Z'for poly in polys for ring in poly)
rows=[{k:f[k]for k in ['code','name','region']}|{'path':path(f['geometry'])}for f in africa]
meta={'country_url':'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson','place_url':'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson','license_url':'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/LICENSE.md','access_date':'2026-10-25','projection':'Equirectangular; x=24+(longitude+20)*9.2; y=24+(38-latitude)*9.2; three decimal SVG units','scale':'Natural Earth 1:110m admin0, 1:10m populated places','source_sha256':{n:hashlib.sha256((source/n).read_bytes()).hexdigest()for n in ['countries.geojson','places.geojson','license.md']}}
(dest/'provenance.json').write_text(json.dumps(meta,indent=2)+'\n')
(dest/'map-data.ts').write_text('// Generated by scripts/generate-africa-map.py from Natural Earth; public domain.\nexport const outlines = '+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n')
